const phrasePattern = new RegExp(Object.keys(english).sort((a, b) => b.length - a.length).map((key) => key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|"), "g");
export function t(value: string, locale: Locale = getLocale()): string {
  if (locale === "ja" || !/[ぁ-龯。、（）]/.test(value)) return value;
  return value.replace(phrasePattern, (match) => english[match]).replace(/（/g, " (").replace(/）/g, ")").replace(/。/g, ". ").replace(/、/g, ", ");
}
/** Localize rendered copy without translating IDs, form values or API payloads. */
export function localizeElement(root: HTMLElement): void {
  if (getLocale() === "ja") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement?.closest("script, style")) continue;
    const value = node.nodeValue || "";
    const translated = t(value, "en");
    if (translated !== value) node.nodeValue = translated;
  }
  for (const element of [root, ...root.querySelectorAll<HTMLElement>("[aria-label], [title], [alt]")]) {
    for (const attribute of ["aria-label", "title", "alt"]) {
      const value = element.getAttribute(attribute);
      if (value !== null) {
        const translated = t(value, "en");
        if (translated !== value) element.setAttribute(attribute, translated);
      }
    }
  }
}
