/** Browser language controls presentation only; simulation and provider IDs stay stable. */
export type Locale = "ja" | "en";
export interface LanguageEnvironment { languages?: readonly string[]; language?: string; userAgent?: string }
export function detectLocale(environment: LanguageEnvironment): Locale {
  const language = environment.languages?.find((value) => value.trim())?.trim() || environment.language?.trim();
  if (language) return /^ja(?:[-_]|$)/i.test(language) ? "ja" : "en";
  // Legacy UAs sometimes included a locale. Modern UAs usually do not.
  return /(?:^|[; (])ja(?:[-_]JP)?(?=[; )]|$)/i.test(environment.userAgent || "") ? "ja" : "en";
}
export function getLocale(): Locale {
  return typeof navigator === "undefined" ? "en" : detectLocale(navigator);
}

